#!/usr/bin/env python3
"""Generate the committed Claude Code pointers for the harness.

Writes, inside this repo:
  .claude/agents/<role>.md           one subagent per role in harness/roles/
  .claude/skills/<playbook>/SKILL.md one skill per playbook in harness/playbooks/

Each file is a pointer: its body tells Claude Code to read the role or
playbook file by its repo-relative path, so editing the role or playbook
needs no regeneration. Re-run (and commit the result) when a role or
playbook is added, renamed or removed, or when its `description`, `tools`
or `reasoning` changes. See harness/README.md, "Claude Code".

The pointers live in the repo, not in ~/.claude, so they apply only inside
SmartMetroService and never collide with another project's roles of the
same name.

Usage: python harness/setup/claude-code-agents.py
"""
import json
import pathlib

HARNESS = pathlib.Path(__file__).resolve().parent.parent
REPO_ROOT = HARNESS.parent
AGENTS_DIR = REPO_ROOT / ".claude" / "agents"
SKILLS_DIR = REPO_ROOT / ".claude" / "skills"
# Neutral capability (harness/README.md) -> Claude Code tools. Some
# Claude Code builds search through the shell and have no Grep or Glob
# tool, so `search` also grants Bash.
TOOLS = {
    "read": ["Read"],
    "search": ["Grep", "Glob", "Bash"],
    "edit": ["Edit", "Write"],
    "run": ["Bash"],
    "web": ["WebFetch", "WebSearch"],
}
# Tier (harness/README.md, "Model tiers and the delivery pipeline") ->
# Claude Code model alias.
MODEL = {"high": "opus", "standard": "sonnet", "fast": "haiku"}
# orchestrator delegates to other roles, and a Claude Code subagent
# cannot start subagents: it runs in the main session instead.
SKIP = {"README", "orchestrator"}
MARKER = "<!-- generated by harness/setup/claude-code-agents.py; edit the role or playbook, not this file -->"


def read(path):
    return path.read_text(encoding="utf-8")


def frontmatter(text):
    lines = text.replace("\r\n", "\n").split("\n")
    if lines[0] != "---":
        raise ValueError("no frontmatter")
    fields, key = {}, None
    for line in lines[1:]:
        if line == "---":
            return fields
        if line.startswith((" ", "\t")) and key:
            fields[key] = (fields[key] + " " + line.strip()).strip()
        elif ":" in line:
            key, value = line.split(":", 1)
            key, value = key.strip(), value.split(" #", 1)[0].strip()
            fields[key] = "" if value in (">-", ">", "|") else value
    raise ValueError("unterminated frontmatter")


def generated(path):
    """True when path is a file this script wrote: its body starts with MARKER."""
    if path.is_symlink() or not path.is_file():
        return False
    try:
        lines = read(path).replace("\r\n", "\n").split("\n")
    except (OSError, UnicodeDecodeError):
        return False
    closing = lines.index("---", 1) if lines[:1] == ["---"] and "---" in lines[1:] else None
    return closing is not None and lines[closing + 1 : closing + 2] == [MARKER]


def tools_for(fields):
    caps = [c.strip() for c in fields.get("tools", "").split(",") if c.strip()]
    names = []
    for cap in caps:
        for tool in TOOLS[cap]:
            if tool not in names:
                names.append(tool)
    # No `tools` field means whatever the tool grants by default.
    return names or None, not caps or "edit" in caps


def agent_body(name, can_edit):
    edit_rule = (
        "Edit files only inside a git worktree under the shared "
        "`worktrees/` folder, never in a primary checkout."
        if can_edit
        else "Do not change any file. Use the shell only for read-only "
        "commands such as `git diff`, `git log` and `gh ... view`."
    )
    return f"""{MARKER}

You are the `{name}` role of the SmartMetroService agent harness.

1. Read `harness/roles/{name}.md` in full before anything else, from the
   checkout or worktree you were given. That file is your instructions;
   follow it.
2. Where it points at `AGENTS.md`, `golden-principles.md` or `docs/`,
   read the ones in that same checkout or worktree; they describe the
   code you are working on.
3. You run as a subagent and cannot ask the user anything. Never write
   to GitHub: no reviews, comments, thread replies or resolves, issue,
   label or PR changes, and no push, even where the role file says to.
   Put what you would post in your report; the caller asks the user.
4. Run no `gh` command that changes anything, and touch nothing in
   production. Never run tests outside `scripts/ci.sh` (they delete the
   database they connect to). Put such a command in your report instead.
5. {edit_rule}
"""


def skill_body(name):
    return f"""{MARKER}

Read `harness/playbooks/{name}.md` in full before doing anything else, then
follow it.
"""


def write_if_ours(target, text, written):
    if (target.exists() or target.is_symlink()) and not generated(target):
        print(f"skipped {target.relative_to(REPO_ROOT)}: not written by this script")
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8", newline="\n")
    written.add(target)
    print(f"wrote {target.relative_to(REPO_ROOT)}")


def main():
    written = set()

    for role in sorted((HARNESS / "roles").glob("*.md")):
        if role.stem in SKIP:
            continue
        fields = frontmatter(read(role))
        name = fields["name"]
        if name != role.stem:
            raise ValueError(f"{role}: name {name!r} does not match the filename")
        tools, can_edit = tools_for(fields)
        head = ["---", f"name: {name}",
                f"description: {json.dumps(fields['description'], ensure_ascii=False)}"]
        if tools:
            head.append(f"tools: {', '.join(tools)}")
        head += [f"model: {MODEL.get(fields.get('reasoning'), 'inherit')}", "---"]
        write_if_ours(AGENTS_DIR / f"{name}.md", "\n".join(head) + "\n" + agent_body(name, can_edit), written)

    for playbook in sorted((HARNESS / "playbooks").glob("*.md")):
        fields = frontmatter(read(playbook))
        name = fields["name"]
        if name != playbook.stem:
            raise ValueError(f"{playbook}: name {name!r} does not match the filename")
        head = ["---", f"name: {name}",
                f"description: {json.dumps(fields['description'], ensure_ascii=False)}", "---"]
        write_if_ours(SKILLS_DIR / name / "SKILL.md", "\n".join(head) + "\n" + skill_body(name), written)

    # A pointer whose role or playbook was removed or renamed goes too.
    for stale in list(AGENTS_DIR.glob("*.md")) + list(SKILLS_DIR.glob("*/SKILL.md")):
        if stale not in written and generated(stale):
            stale.unlink()
            print(f"removed {stale.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
